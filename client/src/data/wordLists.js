/**
 * Generate random text based on difficulty and word count
 */
export const generateText = ({ difficulty = 'medium', wordCount = 50, category = 'english' }) => {
  let wordBank

  if (category === 'programming' || category === 'javascript' || category === 'python') {
    return PROGRAMMING_SNIPPETS[Math.floor(Math.random() * PROGRAMMING_SNIPPETS.length)]
  }

  if (category === 'quotes') {
    return QUOTES[Math.floor(Math.random() * QUOTES.length)]
  }

  switch (difficulty) {
    case 'easy': wordBank = WORDS_EASY; break
    case 'hard': wordBank = WORDS_HARD; break
    case 'expert': wordBank = WORDS_EXPERT; break
    default: wordBank = WORDS_MEDIUM
  }

  const words = []
  for (let i = 0; i < wordCount; i++) {
    words.push(wordBank[Math.floor(Math.random() * wordBank.length)])
  }
  return words.join(' ')
}

